import type { ItemStatus, LyricLine } from "../types.ts";

export function formatTimeDisplay(sec: number): string {
  const safe = Math.max(0, Number(sec) || 0);
  const mins = Math.floor(safe / 60);
  const rem = safe - mins * 60;
  return `${String(mins).padStart(2, "0")}:${rem.toFixed(3).padStart(6, "0")}`;
}

export function formatLrcTimestamp(sec: number): string {
  const safe = Math.max(0, Number(sec) || 0);
  const mins = Math.floor(safe / 60);
  const rem = safe - mins * 60;
  return `[${String(mins).padStart(2, "0")}:${rem.toFixed(2).padStart(5, "0")}]`;
}

export function formatAssTimestamp(sec: number): string {
  const safe = Math.max(0, Number(sec) || 0);
  const totalCentis = Math.round(safe * 100);
  const hours = Math.floor(totalCentis / 360000);
  const remAfterHours = totalCentis - hours * 360000;
  const mins = Math.floor(remAfterHours / 6000);
  const remAfterMins = remAfterHours - mins * 6000;
  const secs = Math.floor(remAfterMins / 100);
  const centis = remAfterMins - secs * 100;
  return `${hours}:${String(mins).padStart(2, "0")}:${String(secs).padStart(2, "0")}.${String(centis).padStart(2, "0")}`;
}

export function parseAssTimestamp(raw: string): number | null {
  const trimmed = String(raw || "").trim();
  const match = /^(?:(\d+):)?(\d{1,2}):(\d{1,2}(?:\.\d+)?)$/.exec(trimmed);
  if (!match) return null;
  const hours = match[1] ? Number.parseInt(match[1], 10) : 0;
  const mins = Number.parseInt(match[2], 10);
  const secs = Number.parseFloat(match[3]);
  if (
    !Number.isFinite(hours) ||
    !Number.isFinite(mins) ||
    !Number.isFinite(secs)
  ) {
    return null;
  }
  return Number((hours * 3600 + mins * 60 + secs).toFixed(3));
}

export function parseLrcTimestamp(raw: string): number | null {
  const trimmed = String(raw || "")
    .trim()
    .replace(/^\[|\]$/g, "");
  const match = /^(\d{1,3}):(\d{1,2}(?:\.\d+)?)$/.exec(trimmed);
  if (!match) return null;
  const mins = Number.parseInt(match[1], 10);
  const secs = Number.parseFloat(match[2]);
  if (!Number.isFinite(mins) || !Number.isFinite(secs)) return null;
  return Number((mins * 60 + secs).toFixed(3));
}

export function exportLyricsToLrc(lines: LyricLine[]): string {
  const sorted = [...lines].sort((a, b) => a.start_sec - b.start_sec);
  const out = [
    "[ti:Try Me]",
    "[ar:Kero Kero Bonito]",
    "[al:Bonito Generation]",
    "[length:03:29.72]",
    "[by:Try Me Workbench Local Alignment]",
    "",
  ];
  for (const line of sorted) {
    out.push(`${formatLrcTimestamp(line.start_sec)} ${line.text}`);
  }
  if (sorted.length > 0) {
    out.push(`${formatLrcTimestamp(sorted[sorted.length - 1].end_sec)} `);
  }
  return out.join("\n") + "\n";
}

export function exportLyricsToAss(lines: LyricLine[]): string {
  const sorted = [...lines].sort((a, b) => a.start_sec - b.start_sec);
  const header = [
    "[Script Info]",
    "; Script generated by Try Me Multi-Track Timeline Workbench",
    "; Round-trip compatible with Aegisub (Actor = Lyric ID, Effect = Section|Bar|Status)",
    "Title: Kero Kero Bonito - Try Me (Lyrics Alignment)",
    "ScriptType: v4.00+",
    "WrapStyle: 0",
    "ScaledBorderAndShadow: yes",
    "YCbCr Matrix: TV.709",
    "PlayResX: 1920",
    "PlayResY: 1080",
    "Audio File: try-me.flac",
    "",
    "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
    "Style: Default,Arial,56,&H00FFFFFF,&H000000FF,&H001E293B,&H80000000,-1,0,0,0,100,100,0,0,1,2.5,1,2,40,40,56,1",
    "Style: Confirmed,Arial,56,&H0080DE4A,&H000000FF,&H001E293B,&H80000000,-1,0,0,0,100,100,0,0,1,2.5,1,2,40,40,56,1",
    "Style: Candidate,Arial,56,&H00F979E8,&H000000FF,&H001E293B,&H80000000,-1,0,0,0,100,100,0,0,1,2.5,1,2,40,40,56,1",
    "",
    "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
  ];

  for (const line of sorted) {
    const startStr = formatAssTimestamp(line.start_sec);
    const endStr = formatAssTimestamp(line.end_sec);
    const styleName = line.status === "confirmed" ? "Confirmed" : "Candidate";
    const actor = line.id || "";
    const effect = `${line.section_id || "P001"}|Bar${line.bar || 1}|${line.status || "candidate"}`;
    const cleanText = String(line.text || "").replace(/\r?\n/g, "\\N");
    header.push(
      `Dialogue: 0,${startStr},${endStr},${styleName},${actor},0,0,0,${effect},${cleanText}`,
    );
  }
  return header.join("\n") + "\n";
}

export function parseAssToLyrics(
  assContent: string,
  existingLines: LyricLine[] = [],
): LyricLine[] {
  const existingById = new Map<string, LyricLine>();
  for (const l of existingLines) {
    existingById.set(l.id, l);
  }

  const parsedDialogues: Array<{
    startSec: number;
    endSec: number;
    style: string;
    actor: string;
    effect: string;
    text: string;
  }> = [];

  const rawLines = String(assContent || "").split(/\r?\n/);
  for (const rawLine of rawLines) {
    const trimmed = rawLine.trim();
    if (!trimmed.startsWith("Dialogue:")) continue;
    const afterPrefix = trimmed.slice("Dialogue:".length).trim();
    // Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
    const parts: string[] = [];
    let rest = afterPrefix;
    for (let i = 0; i < 9; i += 1) {
      const commaIdx = rest.indexOf(",");
      if (commaIdx === -1) break;
      parts.push(rest.slice(0, commaIdx).trim());
      rest = rest.slice(commaIdx + 1);
    }
    if (parts.length < 9) continue;
    const startSec = parseAssTimestamp(parts[1]);
    const endSec = parseAssTimestamp(parts[2]);
    if (startSec === null || endSec === null || endSec <= startSec) continue;
    // Strip ASS override tags like {\pos(...)} while unescaping \N
    const text = rest
      .replace(/\{[^}]*\}/g, "")
      .replace(/\\N/gi, " ")
      .trim();
    if (!text) continue;
    parsedDialogues.push({
      startSec,
      endSec,
      style: parts[3],
      actor: parts[4],
      effect: parts[8],
      text,
    });
  }

  if (parsedDialogues.length === 0) {
    throw new Error("未在 .ass 文件中解析到有效的 Dialogue 字幕行");
  }

  const result: LyricLine[] = [];
  for (let i = 0; i < parsedDialogues.length; i += 1) {
    const d = parsedDialogues[i];
    const fallbackId = `L${String(i + 1).padStart(3, "0")}`;
    const candidateId = /^L\d+$/i.test(d.actor)
      ? d.actor.toUpperCase()
      : fallbackId;
    const prev = existingById.get(candidateId) || existingLines[i] || null;

    let sectionId = prev?.section_id || "P002";
    let bar = prev?.bar || 1;
    let status: ItemStatus = prev?.status || "candidate";

    if (d.effect) {
      const effParts = d.effect.split("|");
      if (effParts[0] && /^P\d+$/i.test(effParts[0])) {
        sectionId = effParts[0].toUpperCase();
      }
      const barMatch = /Bar(\d+)/i.exec(d.effect);
      if (barMatch) {
        bar = Number.parseInt(barMatch[1], 10);
      }
      if (d.effect.includes("confirmed") || d.style === "Confirmed") {
        status = "confirmed";
      }
    } else if (d.style === "Confirmed") {
      status = "confirmed";
    }

    // If start or end changed compared to existing candidate, mark as confirmed or keep status
    if (
      prev &&
      (Math.abs(prev.start_sec - d.startSec) >= 0.015 ||
        Math.abs(prev.end_sec - d.endSec) >= 0.015)
    ) {
      status = "confirmed";
    }

    result.push({
      id: prev?.id || candidateId,
      index: i + 1,
      section_id: sectionId,
      bar,
      start_sec: d.startSec,
      end_sec: d.endSec,
      lrc_start_sec: prev?.lrc_start_sec ?? d.startSec,
      vocal_onset_sec: prev?.vocal_onset_sec ?? null,
      origin_candidate_id: prev?.origin_candidate_id ?? null,
      text: d.text,
      lang:
        prev?.lang || (/[\u3040-\u30ff\u4e00-\u9faf]/.test(d.text) ? "ja" : "en"),
      status,
      note: prev?.note || "",
    });
  }

  return result;
}

export function parseLrcToLyrics(
  lrcContent: string,
  existingLines: LyricLine[] = [],
  totalDurationSec = 209.719,
): LyricLine[] {
  const timedEntries: Array<{ timeSec: number; text: string }> = [];
  const rawLines = String(lrcContent || "").split(/\r?\n/);

  for (const rawLine of rawLines) {
    const match = /^\[(\d{1,3}:\d{1,2}(?:\.\d+)?)\](.*)$/.exec(rawLine.trim());
    if (!match) continue;
    const t = parseLrcTimestamp(match[1]);
    if (t === null) continue;
    timedEntries.push({
      timeSec: t,
      text: match[2].trim(),
    });
  }

  timedEntries.sort((a, b) => a.timeSec - b.timeSec);
  const nonEmpty = timedEntries.filter((e) => e.text.length > 0);
  if (nonEmpty.length === 0) {
    throw new Error("未在 .lrc 文件中解析到有效的带时间戳歌词行");
  }

  const result: LyricLine[] = [];
  for (let i = 0; i < nonEmpty.length; i += 1) {
    const cur = nonEmpty[i];
    // Find the next timestamp in timedEntries (which might be a blank end tag or the next lyric line)
    const rawIdx = timedEntries.indexOf(cur);
    const nextEntry =
      rawIdx !== -1 && rawIdx + 1 < timedEntries.length
        ? timedEntries[rawIdx + 1]
        : null;
    const prev = existingLines[i] || null;
    const startSec = cur.timeSec;
    const fallbackEnd =
      nextEntry && nextEntry.timeSec > startSec + 0.05
        ? nextEntry.timeSec
        : prev && prev.end_sec > startSec + 0.05
          ? prev.end_sec
          : Math.min(totalDurationSec, startSec + 3.0);

    result.push({
      id: prev?.id || `L${String(i + 1).padStart(3, "0")}`,
      index: i + 1,
      section_id: prev?.section_id || "P002",
      bar: prev?.bar || 1,
      start_sec: Number(startSec.toFixed(3)),
      end_sec: Number(fallbackEnd.toFixed(3)),
      lrc_start_sec: startSec,
      vocal_onset_sec: prev?.vocal_onset_sec ?? null,
      origin_candidate_id: prev?.origin_candidate_id ?? null,
      text: cur.text,
      lang:
        prev?.lang ||
        (/[\u3040-\u30ff\u4e00-\u9faf]/.test(cur.text) ? "ja" : "en"),
      status: prev?.status || "candidate",
      note: prev?.note || "",
    });
  }

  return result;
}
